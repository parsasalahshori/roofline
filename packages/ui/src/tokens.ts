export type ColorScheme = 'light' | 'dark';

/** Every token for a theme: the light set, with the dark theme's changes laid over it. */
export function tokensFor(scheme: ColorScheme): Record<TokenName, string> {
  return scheme === 'dark' ? { ...tokens, ...darkTokens } : { ...tokens };
}
